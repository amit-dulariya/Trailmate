import { useState } from 'react';
import { Check, Clock3, MapPin, ShieldCheck, Backpack, ListChecks, Sparkles, CalendarDays } from 'lucide-react';

function Checklist({ items = [] }) {
  const [checked, setChecked] = useState([]);
  return (
    <ul className="checklist">
      {items.map((item, index) => {
        const done = checked.includes(index);
        return (
          <li key={`${item}-${index}`}>
            <button type="button" className={`check-row ${done ? 'done' : ''}`} onClick={() => setChecked(current => done ? current.filter(i => i !== index) : [...current, index])}>
              <span className="checkbox">{done && <Check size={13} />}</span>
              <span>{item}</span>
            </button>
          </li>
        );
      })}
    </ul>
  );
}

export default function PlanResults({ plan, activityLabel, onReset }) {
  if (!plan) return null;
  const prep = Array.isArray(plan.prep) ? plan.prep : [];
  const checklist = Array.isArray(plan.checklist) ? plan.checklist : [];
  const safety = Array.isArray(plan.safety) ? plan.safety : [];
  const schedule = Array.isArray(plan.schedule) ? plan.schedule : [];

  return (
    <section className="results-section" id="your-plan" aria-live="polite">
      <div className="results-heading">
        <div>
          <span className="eyebrow"><Sparkles size={14} /> YOUR OUTDOOR PLAN</span>
          <h2>Made for your kind of outside.</h2>
          <p>A practical plan generated by your local Ollama model. Check local conditions before heading out.</p>
        </div>
        <button type="button" className="text-button" onClick={onReset}>Edit preferences ↗</button>
      </div>

      <article className="plan-hero">
        <div className="plan-hero-copy">
          <span className="plan-tag">{activityLabel} · {plan.duration}</span>
          <h3>{plan.title}</h3>
          <p>{plan.intro}</p>
          <div className="plan-meta"><span><Clock3 size={16} /> {plan.duration}</span><span><MapPin size={16} /> General suggestion</span></div>
        </div>
        <div className="plan-illustration" aria-hidden="true">
          <div className="sun"></div><div className="hill hill-back"></div><div className="hill hill-front"></div>
          <span className="illustration-leaf leaf-one">✳</span><span className="illustration-leaf leaf-two">✦</span>
        </div>
      </article>

      <div className="plan-note"><span className="note-icon"><MapPin size={18} /></span><div><strong>Where to go</strong><p>{plan.location}</p><small className="disclaimer">General suggestion only — no live route or venue data is used.</small></div></div>
      {schedule.length > 0 && <article className="plan-card schedule-card"><div className="section-title"><span className="section-icon prep"><CalendarDays size={18} /></span><div><h3>Your time plan</h3><p>A flexible outline for your available time</p></div></div><ul className="bullet-list">{schedule.map((item, index) => <li key={`${item}-${index}`}>{item}</li>)}</ul></article>}
      <div className="plan-grid">
        <article className="plan-card">
          <div className="section-title"><span className="section-icon prep"><Backpack size={18} /></span><div><h3>Before you go</h3><p>A few easy prep steps</p></div></div>
          <ul className="bullet-list">{prep.map((item, index) => <li key={`${item}-${index}`}>{item}</li>)}</ul>
        </article>
        <article className="plan-card">
          <div className="section-title"><span className="section-icon checklist-icon"><ListChecks size={18} /></span><div><h3>Your activity checklist</h3><p>Tap each item as you go</p></div></div>
          <Checklist items={checklist} />
        </article>
        <article className="plan-card safety-card">
          <div className="section-title"><span className="section-icon safety"><ShieldCheck size={18} /></span><div><h3>Stay safe out there</h3><p>Enjoy the outdoors thoughtfully</p></div></div>
          <ul className="bullet-list">{safety.map((item, index) => <li key={`${item}-${index}`}>{item}</li>)}</ul>
        </article>
      </div>
      <div className="gentle-reminder"><span>🌿</span><p><strong>A gentle reminder</strong>{plan.levelNote}</p></div>
    </section>
  );
}
